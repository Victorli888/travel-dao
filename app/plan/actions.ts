"use server";

import { redirect } from "next/navigation";
import { revalidatePath } from "next/cache";
import { AppError } from "@/lib/api/errors";
import { requireUserEmail } from "@/lib/auth/session";
import { createTrip } from "@/lib/itinerary";
import { CreateDatedTripSchema, parseInput } from "@/lib/itinerary/schemas";

/**
 * There is no `/api/trips` and should not be one — `lib/itinerary/index.ts`
 * says so, and the data layer is built for Server Actions calling it
 * directly. This is the whole transport layer for Frame 0.
 */

/**
 * `useActionState`'s state. `null` is "nothing has gone wrong yet".
 *
 * The initial value lives at the `useActionState` call site, not here. A
 * `"use server"` module may export **only async functions** — Next wraps every
 * export in `ensureServerEntryExports`, which throws `A "use server" file can
 * only export async functions, found object.` on anything else. That check is
 * at runtime, so `next build` passes and the failure lands as a component that
 * silently never hydrates. An exported `interface` is fine: types are erased
 * and never become a runtime export.
 */
export interface NewTripState {
  error: string | null;
}

/**
 * Creates the trip and opens it. **One write**, because the Neon HTTP driver
 * has no interactive transactions and a second write here could half-fail
 * silently. The day rows are generated by `/plan/[tripId]` on first view,
 * where the insert is idempotent and a reload retries it.
 */
export async function createTripAction(
  _prev: NewTripState,
  formData: FormData,
): Promise<NewTripState> {
  let tripId: string;

  try {
    const email = await requireUserEmail();
    // Coerced to strings first: a missing field is `null`, and Zod would
    // report that as a type error rather than "Give the trip a name."
    const draft = parseInput(CreateDatedTripSchema, {
      name: String(formData.get("name") ?? ""),
      startDate: String(formData.get("startDate") ?? ""),
      endDate: String(formData.get("endDate") ?? ""),
    });

    tripId = (await createTrip(email, draft)).id;
  } catch (error) {
    // `ValidationError` from the schema, and the allow-list `NOT_ALLOWED`
    // that `createTrip` already translates out of `trips_user_email_fkey`.
    if (error instanceof AppError) return { error: error.message };
    console.error("Unhandled createTripAction error:", error);
    return { error: "Something went wrong creating the trip." };
  }

  // Outside the `try` on purpose: `redirect` signals by throwing, and a
  // catch above would swallow it and leave the form looking inert.
  revalidatePath("/plan");
  redirect(`/plan/${tripId}`);
}
